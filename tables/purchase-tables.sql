-- Purchase request workflow tables
-- Amounts are stored as whole Toman units (BIGINT).
-- Review this script against your ProcessMaker workspace DB policy before execution.

CREATE TABLE IF NOT EXISTS PURCHASE_REQUESTS (
  ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  REQUEST_NUMBER VARCHAR(40) NOT NULL,
  REQUESTER_NAME VARCHAR(160) NOT NULL,
  REQUESTER_PHONE VARCHAR(20) NOT NULL,
  PRODUCT_NAME VARCHAR(180) NOT NULL,
  PRODUCT_DESCRIPTION TEXT NULL,
  QUANTITY BIGINT UNSIGNED NOT NULL,
  UNIT_PRICE BIGINT UNSIGNED NOT NULL,
  TOTAL_AMOUNT BIGINT UNSIGNED NOT NULL,
  REQUEST_DATE DATETIME NOT NULL,
  REQUEST_STATUS VARCHAR(30) NOT NULL,
  REJECTION_REASON VARCHAR(500) NULL,
  CASE_UID CHAR(32) NOT NULL,
  PRIMARY KEY (ID),
  UNIQUE KEY uq_purchase_request_number (REQUEST_NUMBER),
  UNIQUE KEY uq_purchase_request_case (CASE_UID),
  CHECK (QUANTITY > 0),
  CHECK (UNIT_PRICE > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PURCHASE_REVIEWS (
  ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  REQUEST_NUMBER VARCHAR(40) NOT NULL,
  TOTAL_AMOUNT BIGINT UNSIGNED NOT NULL,
  THRESHOLD_AMOUNT BIGINT UNSIGNED NOT NULL,
  REVIEW_RESULT VARCHAR(20) NOT NULL,
  REVIEW_REASON VARCHAR(500) NOT NULL,
  REVIEW_DATE DATETIME NOT NULL,
  CASE_UID CHAR(32) NOT NULL,
  PRIMARY KEY (ID),
  UNIQUE KEY uq_purchase_review_case (CASE_UID),
  KEY ix_purchase_review_request (REQUEST_NUMBER)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PURCHASE_PAYMENTS (
  ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  REQUEST_NUMBER VARCHAR(40) NOT NULL,
  PAYMENT_AMOUNT BIGINT UNSIGNED NOT NULL,
  PAYMENT_STATUS VARCHAR(30) NOT NULL,
  PAYMENT_METHOD VARCHAR(30) NOT NULL,
  PAYMENT_REFERENCE VARCHAR(120) NULL,
  PAYMENT_DATE DATETIME NULL,
  PAYMENT_DESCRIPTION TEXT NULL,
  CASE_UID CHAR(32) NOT NULL,
  PRIMARY KEY (ID),
  UNIQUE KEY uq_purchase_payment_case (CASE_UID),
  KEY ix_purchase_payment_request (REQUEST_NUMBER)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Recommended application-level status values:
-- PURCHASE_REQUESTS.REQUEST_STATUS: APPROVED, REJECTED, PAID
-- PURCHASE_REVIEWS.REVIEW_RESULT: APPROVED, REJECTED
-- PURCHASE_PAYMENTS.PAYMENT_STATUS: UNPAID, PAID
-- Payment method values: CARD_TO_CARD, BANK_TRANSFER, CASH, OTHER
